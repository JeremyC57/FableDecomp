#!/usr/bin/env python3
"""Generates overlay_font.inc: ASCII 32..126 as 8x16 one-bit glyphs (16 bytes each, one byte per
row, bit 7 = left pixel), rendered from DejaVu Sans Mono Bold (public, Bitstream Vera licence).

usage: gen_font.py <DejaVuSansMono-Bold.ttf> <out .inc>
"""
import sys

from PIL import Image, ImageDraw, ImageFont


def main():
    font = ImageFont.truetype(sys.argv[1], 13)
    rows = []
    for code in range(32, 127):
        img = Image.new("L", (8, 16), 0)
        ImageDraw.Draw(img).text((0, 0), chr(code), font=font, fill=255)
        data = []
        for y in range(16):
            b = 0
            for x in range(8):
                if img.getpixel((x, y)) > 110:
                    b |= 0x80 >> x
            data.append(b)
        rows.append("    {" + ", ".join(f"0x{b:02X}" for b in data) + f"}},  // '{chr(code) if code != 92 else 'backslash'}'")
    with open(sys.argv[2], "w") as f:
        f.write("// Generated by gen_font.py: ASCII 32..126, 8x16, one byte per row. Do not edit.\n")
        f.write("static const unsigned char kOverlayFont[95][16] = {\n" + "\n".join(rows) + "\n};\n")


if __name__ == "__main__":
    main()
