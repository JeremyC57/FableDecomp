#!/usr/bin/env python3
"""Generates the GL command-queue wrappers for the OpenGL ES renderer.

The renderer's gl* calls are issued by the game thread; with the queue they are recorded
and replayed by a render thread that owns the context (gl_queue.cpp), so the driver's
per-draw CPU work overlaps the game's. Reads the prototypes from GLES3/gl3.h and emits:

  gl_queue_gen.hpp  the op enum, the argument records, `namespace real` (the loaded entry
                    points) and the inline wrappers under the GL names
  gl_queue_gen.inc  the entry point definitions and the replay switch (gl_queue.cpp)

Run from this directory: python3 gen_gl_queue.py [/usr/include/GLES3/gl3.h]
"""
import re
import sys

FUNCS = """glActiveTexture glAttachShader glBeginQuery glBindBuffer glBindFramebuffer glBindRenderbuffer
glBindSampler glBindTexture glBindVertexArray glBlendColor glBlendEquation glBlendFunc glBlitFramebuffer
glBufferData glBufferSubData glCheckFramebufferStatus glClear glClearColor glClearDepthf glClearStencil
glColorMask glCompileShader glCreateProgram glCreateShader glCullFace glDeleteBuffers glDeleteFramebuffers
glDeleteProgram glDeleteQueries glDeleteRenderbuffers glDeleteSamplers glDeleteShader glDeleteTextures
glDeleteVertexArrays glDepthFunc glDepthMask glDepthRangef glDisable glDisableVertexAttribArray glDrawArrays
glDrawElements glEnable glEnableVertexAttribArray glEndQuery glFinish glFramebufferRenderbuffer
glFramebufferTexture2D glFrontFace glGenBuffers glGenFramebuffers glGenQueries glGenRenderbuffers glGenSamplers
glGenTextures glGenVertexArrays glGenerateMipmap glGetError glGetIntegerv glGetProgramInfoLog glGetProgramiv
glGetQueryObjectuiv glGetShaderInfoLog glGetShaderiv glGetString glGetUniformLocation glInvalidateFramebuffer
glLinkProgram glPixelStorei glPolygonOffset glReadPixels glRenderbufferStorage glRenderbufferStorageMultisample
glSamplerParameteri glScissor glShaderSource glStencilFunc glStencilMask glStencilOp glTexParameteri
glTexParameteriv glTexStorage2D glTexSubImage2D glUniform1f glUniform1i glUniform2f glUniform4f glUniform4fv
glUseProgram glVertexAttribPointer glViewport""".split()

# calls whose result (or output pointer) the caller needs now: the game thread waits for the replay
SYNC = set("""glCheckFramebufferStatus glCreateProgram glCreateShader glFinish glGenBuffers glGenFramebuffers
glGenQueries glGenRenderbuffers glGenSamplers glGenTextures glGenVertexArrays glGetError glGetIntegerv
glGetProgramInfoLog glGetProgramiv glGetQueryObjectuiv glGetShaderInfoLog glGetShaderiv glGetString
glGetUniformLocation glReadPixels""".split())

# calls that read memory the caller may free or reuse: (pointer parameter, byte count expression)
DATA = {
    'glBufferData': ('data', '(size_t)size'),
    'glBufferSubData': ('data', '(size_t)size'),
    'glTexSubImage2D': ('pixels', 'gq::texBytes(width, height, format, type)'),
    'glUniform4fv': ('value', '16 * (size_t)count'),
    'glTexParameteriv': ('params', '16'),
    'glInvalidateFramebuffer': ('attachments', '4 * (size_t)numAttachments'),
    'glDeleteBuffers': ('buffers', '4 * (size_t)n'),
    'glDeleteFramebuffers': ('framebuffers', '4 * (size_t)n'),
    'glDeleteQueries': ('ids', '4 * (size_t)n'),
    'glDeleteRenderbuffers': ('renderbuffers', '4 * (size_t)n'),
    'glDeleteSamplers': ('samplers', '4 * (size_t)count'),
    'glDeleteTextures': ('textures', '4 * (size_t)n'),
    'glDeleteVertexArrays': ('arrays', '4 * (size_t)n'),
}
SPECIAL = {'glShaderSource'}  # hand-written below
# object names come from a pool the render thread refills 64 at a time (one round trip per 64
# objects instead of one per object while a level streams in)
POOL = {f: 'GEN_' + f[5].lower() + f[6:] for f in
        'glGenBuffers glGenFramebuffers glGenQueries glGenRenderbuffers glGenSamplers glGenTextures glGenVertexArrays'.split()}
OPTIONAL = {'glInvalidateFramebuffer'}  # may be missing from the driver: a no-op then


def parse(header):
    protos = {}
    rx = re.compile(r'GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(gl\w+)\s*\((.*?)\);')
    for m in rx.finditer(open(header).read()):
        ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
        plist = []
        if params and params != 'void':
            for p in params.split(','):
                p = p.strip()
                mm = re.match(r'(.+?)\s*(\**)\s*(\w+)$', p)
                typ = (mm.group(1) + ' ' + mm.group(2)).strip()
                typ = re.sub(r'\s+\*', '*', typ)
                plist.append((typ, mm.group(3)))
        protos[name] = (ret, plist)
    return protos


def main():
    header = sys.argv[1] if len(sys.argv) > 1 else '/usr/include/GLES3/gl3.h'
    protos = parse(header)
    missing = [f for f in FUNCS if f not in protos]
    if missing:
        sys.exit('not in %s: %s' % (header, ' '.join(missing)))
    hpp = ['// Generated by gen_gl_queue.py: do not edit. The GL names below are wrappers that record',
           '// the call for the render thread (or call the driver directly on that thread / when the',
           '// queue is off); `real` holds the driver entry points.', '#pragma once',
           '#include <GLES3/gl3.h>', '#include <cstring>', '#include "gl_queue.hpp"', '',
           'namespace host::gles {', 'enum GlOp : uint32_t {', '    OP_pad = 0, OP_call, OP_frame,']
    for f in FUNCS:
        hpp.append('    OP_%s,' % f)
    hpp.append('    OP_count')
    hpp.append('};')
    hpp.append('namespace real {')
    for f in FUNCS:
        hpp.append('extern PFN%sPROC %s;' % (f.upper(), f))
    hpp.append('}  // namespace real')
    inc = ['// Generated by gen_gl_queue.py: do not edit (included by gl_queue.cpp).',
           'namespace host::gles {', 'namespace real {']
    for f in FUNCS:
        inc.append('PFN%sPROC %s = nullptr;' % (f.upper(), f))
    inc.append('}  // namespace real')
    inc.append('')
    inc.append('// Replays one record on the render thread.')
    inc.append('void gq::replay(uint32_t op, const void* rec) {')
    inc.append('    switch (op) {')
    for f in FUNCS:
        ret, params = protos[f]
        names = [n for _, n in params]
        args = ', '.join(names)
        sig = ', '.join('%s %s' % (t, n) for t, n in params)
        isSync = f in SYNC
        data = DATA.get(f)
        # the argument record
        hpp.append('struct A_%s {' % f)
        for t, n in params:
            hpp.append('    %s %s;' % (t, n))
        if isSync:
            hpp.append('    gq::Sync* sync;')
        if data:
            hpp.append('    uint32_t bytes; uint32_t isNull;')
        hpp.append('};')
        if f in SPECIAL:
            continue
        if f in POOL:
            hpp.append('inline %s %s(%s) {' % (ret, f, sig))
            hpp.append('    if (gq::direct()) { real::%s(%s); return; }' % (f, args))
            hpp.append('    gq::genNames(gq::%s, %s);' % (POOL[f], args))
            hpp.append('}')
            continue
        # the wrapper
        direct = 'real::%s(%s)' % (f, args)
        if f in OPTIONAL:
            direct = '(real::%s ? real::%s(%s) : (void)0)' % (f, f, args)
        hpp.append('inline %s %s(%s) {' % (ret, f, sig))
        hpp.append('    if (gq::direct()) %s' % (('return %s;' % direct) if ret != 'void' else ('{ %s; return; }' % direct)))
        if f in OPTIONAL:
            hpp.append('    if (!real::%s) return;' % f)
        if data:
            ptr, nbytes = data
            hpp.append('    const size_t bytes_ = %s ? (%s) : 0;' % (ptr, nbytes))
            hpp.append('    A_%s* a = static_cast<A_%s*>(gq::begin(OP_%s, sizeof(A_%s), bytes_));' % (f, f, f, f))
        else:
            hpp.append('    A_%s* a = static_cast<A_%s*>(gq::begin(OP_%s, sizeof(A_%s), 0));' % (f, f, f, f))
        for t, n in params:
            hpp.append('    a->%s = %s;' % (n, n))
        if data:
            ptr, _ = data
            hpp.append('    a->bytes = static_cast<uint32_t>(bytes_); a->isNull = %s == nullptr;' % ptr)
            hpp.append('    if (bytes_) std::memcpy(a + 1, %s, bytes_);' % ptr)
        if isSync:
            hpp.append('    gq::Sync s;')
            hpp.append('    a->sync = &s;')
            hpp.append('    gq::commit();')
            hpp.append('    gq::wait(s);')
            if ret == 'GLuint':
                hpp.append('    return s.u;')
            elif ret == 'GLint':
                hpp.append('    return s.i;')
            elif ret == 'GLenum':
                hpp.append('    return s.e;')
            elif ret == 'const GLubyte*' or ret == 'const GLubyte *':
                hpp.append('    return s.p;')
            elif ret != 'void':
                sys.exit('unhandled return type %s for %s' % (ret, f))
        else:
            hpp.append('    gq::commit();')
        hpp.append('}')
        # the replay case
        callArgs = []
        for t, n in params:
            if data and n == data[0]:
                callArgs.append('(a.isNull ? nullptr : reinterpret_cast<%s>(&a + 1))' % t)
            else:
                callArgs.append('a.' + n)
        call = 'real::%s(%s)' % (f, ', '.join(callArgs))
        inc.append('    case OP_%s: {' % f)
        inc.append('        const A_%s& a = *static_cast<const A_%s*>(rec);' % (f, f))
        if isSync:
            if ret == 'GLuint':
                inc.append('        a.sync->u = %s;' % call)
            elif ret == 'GLint':
                inc.append('        a.sync->i = %s;' % call)
            elif ret == 'GLenum':
                inc.append('        a.sync->e = %s;' % call)
            elif ret.startswith('const GLubyte'):
                inc.append('        a.sync->p = %s;' % call)
            else:
                inc.append('        %s;' % call)
            inc.append('        gq::signal(*a.sync);')
        else:
            if f in OPTIONAL:
                inc.append('        if (real::%s) %s;' % (f, call))
            else:
                inc.append('        %s;' % call)
        inc.append('        break;')
        inc.append('    }')
    # glShaderSource: the strings are concatenated into the record and handed back as one string
    hpp.append('inline void glShaderSource(GLuint shader, GLsizei count, const GLchar* const* string, const GLint* length) {')
    hpp.append('    if (gq::direct()) return real::glShaderSource(shader, count, string, length);')
    hpp.append('    size_t total = 0;')
    hpp.append('    for (GLsizei i = 0; i < count; ++i) total += (length && length[i] >= 0) ? static_cast<size_t>(length[i]) : std::strlen(string[i]);')
    hpp.append('    A_glShaderSource* a = static_cast<A_glShaderSource*>(gq::begin(OP_glShaderSource, sizeof(A_glShaderSource), total + 1));')
    hpp.append('    a->shader = shader; a->count = 1; a->string = nullptr; a->length = nullptr;')
    hpp.append('    char* out = reinterpret_cast<char*>(a + 1);')
    hpp.append('    for (GLsizei i = 0; i < count; ++i) { const size_t n = (length && length[i] >= 0) ? static_cast<size_t>(length[i]) : std::strlen(string[i]); std::memcpy(out, string[i], n); out += n; }')
    hpp.append('    *out = 0;')
    hpp.append('    gq::commit();')
    hpp.append('}')
    inc.append('    case OP_glShaderSource: {')
    inc.append('        const A_glShaderSource& a = *static_cast<const A_glShaderSource*>(rec);')
    inc.append('        const GLchar* src = reinterpret_cast<const GLchar*>(&a + 1);')
    inc.append('        real::glShaderSource(a.shader, 1, &src, nullptr);')
    inc.append('        break;')
    inc.append('    }')
    inc.append('    default: break;')
    inc.append('    }')
    inc.append('}')
    inc.append('')
    inc.append('void (*gq::genFn(int kind))(GLsizei, GLuint*) {')
    inc.append('    switch (kind) {')
    for f, k in POOL.items():
        inc.append('    case gq::%s: return real::%s;' % (k, f))
    inc.append('    default: return nullptr;')
    inc.append('    }')
    inc.append('}')
    inc.append('bool gq::loadReal(void* (*getProc)(const char*)) {')
    for f in FUNCS:
        inc.append('    real::%s = reinterpret_cast<PFN%sPROC>(getProc("%s"));' % (f, f.upper(), f))
    required = ' && '.join('real::' + f for f in FUNCS if f not in OPTIONAL)
    inc.append('    return %s;' % required)
    inc.append('}')
    inc.append('}  // namespace host::gles')
    hpp.append('}  // namespace host::gles')
    open('gl_queue_gen.hpp', 'w').write('\n'.join(hpp) + '\n')
    open('gl_queue_gen.inc', 'w').write('\n'.join(inc) + '\n')
    print('%d entry points, %d synchronous, %d with data' % (len(FUNCS), len(SYNC), len(DATA)))


if __name__ == '__main__':
    main()
