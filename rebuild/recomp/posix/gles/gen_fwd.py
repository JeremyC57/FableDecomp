#!/usr/bin/env python3
"""Generates forwarding method definitions for a class wrapping a D3D9 interface.

usage: gen_fwd.py <mingw include dir> <Interface> <Class> <out .inc> [hand-written method names...]
Each method of <Interface> not named on the command line becomes
  RET STDMETHODCALLTYPE Class::Name(args) { return inner->Name(argnames); }
"""
import re, sys
inc, iface, cls, out = sys.argv[1:5]
hand = set(sys.argv[5:])
src = open(inc + "/d3d9.h").read()
m = re.search(r"DECLARE_INTERFACE_IID_\(%s,\s*\w+,[^)]*\)\s*\{(.*?)\n\};" % iface, src, re.S)
body = m.group(1)
lines = []
for ret, name, args in re.findall(r"STDMETHOD(?:_\((\w+),\s*(\w+)\)|\((\w+)\))\s*\((THIS.*?)\)\s*PURE", body, re.S) and [] or []:
    pass
for ret, name1, name2, args in re.findall(r"STDMETHOD(?:_\((\w+),\s*(\w+)\)|\((\w+)\))\s*\((THIS.*?)\)\s*PURE", body, re.S):
    name = name1 or name2
    ret = ret or "HRESULT"
    args = " ".join(args.split())
    if name in hand or name in ("QueryInterface", "AddRef", "Release"):
        continue
    args = args.strip()
    if args == "THIS":
        params, names = "", ""
    else:
        params = args[len("THIS_"):].strip()
        names = []
        fixed = []
        for i, p in enumerate(params.split(",")):
            p = p.strip()
            toks = p.split()
            last = re.sub(r"\[.*\]", "", toks[-1])
            if len(toks) == 1 or last.endswith("*") or last.endswith("&") or last in ("const",):
                p = p + " a%d" % i
                nm = "a%d" % i
            else:
                nm = last.lstrip("*&")
            fixed.append(p)
            names.append(nm)
        params = ", ".join(fixed)
        names = ", ".join(names)
    lines.append("%s STDMETHODCALLTYPE %s::%s(%s) { return inner->%s(%s); }" % (ret, cls, name, params, name, names))
open(out, "w").write("// generated by gen_fwd.py: forwarding methods of %s\n" % cls + "\n".join(lines) + "\n")
print(len(lines), "methods")
