#!/bin/sh
# Lifts the Xbox default.xbe with the options the Xbox host expects.
#   lift.sh <fable_recomp> <iso folder>/default.xbe <output folder> [lifter options]
set -e
LIFTER="$1"; XBE="$2"; OUT="$3"; shift 3   # further arguments go to the lifter (--trace ADDR ...)
exec "$LIFTER" "$XBE" - "$OUT" "$@" \
  --mmio 0x84E460-0x863200 \
  --safepoints \
  --bucket 14 \
  --hook 0x4B440=hle_CoroSwitch \
  --wrap 0x1FBF0=hle_operator_new \
  --hook 0x86ED4B=hle_XInitDevices \
  --hook 0x86FFFF=hle_XGetDevices \
  --hook 0x870021=hle_XGetDeviceChanges \
  --hook 0x8700F0=hle_XInputOpen \
  --hook 0x870146=hle_XInputClose \
  --hook 0x870152=hle_XInputGetState \
  --hook 0x8701C5=hle_XInputSetState \
  --hook 0x82B6A2=hle_DirectSoundCreate \
  --hook 0x82B6E9=hle_DirectSoundCreateStream \
  --hook 0x829C61=hle_DirectSoundDoWork \
  --hook 0x8285D2=hle_DirectSoundUseLightHRTF \
  --hook 0x8285A1=hle_IDirectSound_Release \
  --hook 0x82B0C7=hle_IDirectSound_CommitDeferredSettings \
  --hook 0x829A73=hle_IDirectSound_SynchPlayback \
  --hook 0x829A1B=hle_IDirectSound_EnableHeadphones \
  --hook 0x82B470=hle_IDirectSound_SetDistanceFactor \
  --hook 0x82B494=hle_IDirectSound_SetDopplerFactor \
  --hook 0x82B4B8=hle_IDirectSound_SetRolloffFactor \
  --hook 0x82B4DC=hle_IDirectSound_SetI3DL2Listener \
  --hook 0x829A37=hle_IDirectSound_SetMixBinHeadroom \
  --hook 0x8299F1=hle_IDirectSound_SetEffectData \
  --hook 0x8299CA=hle_IDirectSound_GetEffectData \
  --hook 0x8299A3=hle_IDirectSound_DownloadEffectsImage \
  --hook 0x829987=hle_IDirectSound_GetCaps \
  --hook 0x829A57=hle_IDirectSound_GetTime \
  --hook 0x82B44C=hle_IDirectSound_CreateSoundBuffer \
  --hook 0x8285BC=hle_IDirectSoundBuffer_Release \
  --hook 0x829B33=hle_IDirectSoundBuffer_Play \
  --hook 0x829B57=hle_IDirectSoundBuffer_PlayEx \
  --hook 0x829B7B=hle_IDirectSoundBuffer_Stop \
  --hook 0x829B93=hle_IDirectSoundBuffer_StopEx \
