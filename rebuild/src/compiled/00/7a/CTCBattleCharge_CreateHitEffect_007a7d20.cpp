void CTCBattleCharge::CreateHitEffect()
{
    CThingCreatureBase* parent_creature = GFDebugDynamicCast(&GetParentThing(), (CThingCreatureBase*)0);
    parent_creature->MakeNoise("SIMPLE_NOISE");
    std::vector<CThingPhysical*> victims;
    C2DBoxI area_of_effect(parent_creature->GetPos().ToC2DCoordI(), (long)RadiusOfEffect);
    PeekThingSearchTools().GetAllThingsInRoughArea<CThingPhysical>(area_of_effect,
        GFFilter_Bind3(CThingFilter_In3DRange(parent_creature->GetPos(), RadiusOfEffect),
            CThingFilter_IsNot(*parent_creature), CThingFilter_CanBeHitByEpicSpell()), victims);
    float dragon_radius = RadiusOfEffect;
    CRegion cur_region = GetWorldMap().GetRegion(GetWorldMap().GetLoadedRegion());
    if (cur_region.GetName() == "DragonCliff2") {
        std::vector<CThingPhysical*> dragon_candidates;
        dragon_radius = PDef->DragonExtraGumphRadiusMultiplier * RadiusOfEffect + PDef->DragonExtraGumphRadius;
        C2DBoxI area_of_effect_for_dragon(parent_creature->GetPos().ToC2DCoordI(), (long)dragon_radius);
        PeekThingSearchTools().GetAllThingsInRoughArea<CThingPhysical>(area_of_effect_for_dragon,
            GFFilter_Bind3(CThingFilter_In3DRange(parent_creature->GetPos(), dragon_radius),
                CThingFilter_IsNot(*parent_creature), CThingFilter_HasInstantiationName("CREATURE_DRAGON_01")), dragon_candidates);
        FABLE_RETAIL_ASSERT(dragon_candidates.size() < 2);
        for (long i = 0; i < dragon_candidates.size(); ++i)
            victims.push_back(dragon_candidates[i]);
    }

    for (long c1 = 0; c1 < victims.size(); ++c1) {
        float damage = PDef->BattleChargeDamage[SpellLevel];
        CThingPhysical* pvictim = victims[c1];
        if (pvictim == parent_creature)
            continue;
        if (!NCreatureMode::IsIncapacitated(*pvictim) &&
            std::find(PeopleHit.begin(), PeopleHit.end(), CIntelligentPointer<CThing>(pvictim)) == PeopleHit.end()) {
            FABLE_RETAIL_ASSERT(pvictim->GetTypeFlags() & 4);
            CThingGameObject* pgame_object = GFDebugPDynamicCast(pvictim, (CThingGameObject*)0);
            {
                C3DVector distance_from_parent(pgame_object->GetPos() - parent_creature->GetPos());
                if (CollidedThing != pgame_object) {
                    float dist = distance_from_parent.GetMagnitude();
                    float r = pgame_object->PeekBaseDef().GetInstantiationName() == "CREATURE_DRAGON_01" ? dragon_radius : RadiusOfEffect;
                    float frac = 1.0f - dist/r;
                    damage *= frac;
                }
                if (pgame_object->GetTypeFlags() & 8) {
                    if (IS_THING_ALIVE(PTarget)) {
                        if (IsZTargetting) {
                            if (PTarget.Get() != pvictim && !CTCEnemy::AreThingsEnemies(*PTarget, *pvictim))
                                continue;
                        } else if (!CTCEnemy::AreThingsEnemies(*parent_creature, *pvictim))
                            continue;
                    } else if (!CTCEnemy::AreThingsEnemies(*parent_creature, *pvictim))
                        continue;
                }
                CHitParameters hit_params(0, parent_creature, 0, parent_creature->GetPos(), distance_from_parent, true, false, false, false);
                hit_params.AddDamageWithAttribute(DAMAGE_MELEE, damage);
                hit_params.SetCreateDustParticleEffectOnHit(false);
                pgame_object->OnHit(hit_params);
                CTCEntityEvents* ptc_entity_events;
                if (pgame_object->GetTC(&ptc_entity_events))
                    ptc_entity_events->AddEvent(new NEntityEvents::CEventHitBySpecialAbility(hit_params, HERO_ABILITY_BATTLE_CHARGE));
            }
        }
    }

    C3DVector effect_pos(parent_creature->GetPos());
    if (IS_THING_ALIVE(CollidedThing) && (CollidedThing->GetTypeFlags() & 8))
        effect_pos = CollidedThing->GetPos();
    CEnvironmentSpellEffectInterpolator& interp = GetWorld().GetEnvironment().GetSpellEffectInterpolator();
    void* key = interp.RadialBlurFadeTo(PDef->BattleChargeRadialStartSeconds, NScreenEffect::SCREEN_EFFECT_PRIORITY_SPELL,
        PDef->BattleChargeRadialThreshold, PDef->BattleChargeRadialLength,
        PDef->BattleChargeRadialIntensity, PDef->BattleChargeRadialFade,
        PDef->BattleChargeRadialRange, PDef->BattleChargeRadialTwist);
    interp.RadialBlurSetCenterWorldPos(key, effect_pos);
    interp.RadialBlurFadeOut(PDef->BattleChargeRadialEndSeconds, key);
    CTCSoundPlayer* ptc_sound_player;
    if (parent_creature->GetTC(&ptc_sound_player))
        ptc_sound_player->PlayAttachedCriteria("HERO_ABILITY_BATTLE_CHARGE_COLLISION", true, false, false, -1);
    CDefPointer<const CSpecialEffectsDef> pspecial_effects;
    long effect = 0;
    if (PDef->GetSubDef(&pspecial_effects)) {
        switch (SpellLevel) {
        case 0:
            if (pspecial_effects->GetEffectFromString("ONHIT_EFFECT_LEVEL0", effect))
                CTCSpecialAbilities::CreateParticleEffect(effect, effect_pos);
            if (pspecial_effects->GetEffectFromString("ONHIT_EFFECT_DISPLACEMENT_LEVEL0", effect))
                CTCSpecialAbilities::CreateParticleEffect(effect, effect_pos);
            break;
        case 1:
            if (pspecial_effects->GetEffectFromString("ONHIT_EFFECT_LEVEL1", effect))
                CTCSpecialAbilities::CreateParticleEffect(effect, effect_pos);
            if (pspecial_effects->GetEffectFromString("ONHIT_EFFECT_DISPLACEMENT_LEVEL1", effect))
                CTCSpecialAbilities::CreateParticleEffect(effect, effect_pos);
            break;
        case 2:
            if (pspecial_effects->GetEffectFromString("ONHIT_EFFECT_LEVEL2", effect))
                CTCSpecialAbilities::CreateParticleEffect(effect, effect_pos);
            if (pspecial_effects->GetEffectFromString("ONHIT_EFFECT_DISPLACEMENT_LEVEL2", effect))
                CTCSpecialAbilities::CreateParticleEffect(effect, effect_pos);
            break;
        case 3:
            if (pspecial_effects->GetEffectFromString("ONHIT_EFFECT_LEVEL3", effect))
                CTCSpecialAbilities::CreateParticleEffect(effect, effect_pos);
            if (pspecial_effects->GetEffectFromString("ONHIT_EFFECT_DISPLACEMENT_LEVEL3", effect))
                CTCSpecialAbilities::CreateParticleEffect(effect, effect_pos);
            break;
        }
        if (pspecial_effects->GetEffectFromString("ONHIT_DEBRIS_EFFECT", effect))
            CTCSpecialAbilities::CreateParticleEffect(effect, effect_pos);
    }
    if (GetParentThing().GetType() == 2 && GetParentThing().GetPlayer().IsMainPlayer())
        GFGetSystemManager()->GetInputManager()->GetJoystick(GetParentThing().GetJoystickDeviceNumber()).AddRumble(2,
            CJoystick::CInitRumble(1.0f, 0.0f, 0.0f, 0.4f, false), false);
}

