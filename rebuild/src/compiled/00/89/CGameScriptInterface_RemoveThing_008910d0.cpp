void CGameScriptInterface::RemoveThing(const CScriptThing& thing, bool flag, bool byScript) const
{
    if (thing.IsAlive()) {
        CThing* t = thing.GetPThing();
        if (t && !t->m_dead) {
            if (byScript)
                t->m_killedByScript = true;
            t->Kill(flag);
        }
    }
}