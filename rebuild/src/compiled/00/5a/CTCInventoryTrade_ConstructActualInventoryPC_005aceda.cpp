void CCharString::UnassignString()
{
    CCharStringData* data = PStringData;
    if (data) {
        data->DecRef();
        if (data->GetRefs() <= 0) {
            CCharStringData* released = PStringData;
            if (released)
                delete released;
        }
        PStringData = 0;
    }
}
