void CTCInventoryTrade::InitialiseBuyableItems(std::vector<std::pair<long, long> >& result)
{
    SpecialItemsToDelete.clear();
    long num_items_added = 0;
    CategoryIdent = NInventory::INVENTORY_CATEGORY_IDENTIFIER_TRADE_BUY;
    CTCShop* ptc_shop = 0;
    if (!GetBuildingThing()->GetTC(&ptc_shop)) { FABLE_RETAIL_ASSERT_ARM(false); }
    std::map<long, long> InventoryTradeThingsBuy = ptc_shop->GetStockList();
    const CThingPlayerCreature* pplayer =
        CMainGameComponent::Get()->PeekPlayerManager().GetMainPlayer().PeekPControlledCreature();
    const CTCInventory* ptc_inventory = 0;
    if (!pplayer->PeekTC(&ptc_inventory)) { FABLE_RETAIL_ASSERT_ARM(false); }
    std::vector<std::pair<long, long> > items;
    ptc_inventory->GetAllItems(items);
    if (false) {} else for (long i = 0; i < items.size(); ++i) {
        long item_def_index = items[i].first;
        CDefPointer<const CThingBaseDef> pbase_def;
        if (!GetDefinitionManager().GetDef(item_def_index, &pbase_def)) { FABLE_RETAIL_ASSERT_ARM(false); }
        CDefPointer<const CHeroTitleDef> ptitle_def;
        bool add = false;
        if (CTCInventoryItem::GetTattooCardDef(item_def_index).Get() && ptc_shop->IsTattooShop()) {
            InventoryTradeThingsBuy[item_def_index] = 1;
            add = true;
        } else if (CTCInventoryItem::GetHairCardDef(item_def_index).Get() && ptc_shop->IsBarberShop()) {
            InventoryTradeThingsBuy[item_def_index] = 1;
            add = true;
        } else if (pbase_def->GetSubDef(&ptitle_def) && ptc_shop->IsTitleShop()) {
            InventoryTradeThingsBuy[item_def_index] = 1;
            add = true;
        }
        if (add) {
            std::map<long,long>::iterator found = SpecialItemsToDelete.find(item_def_index);
            if (found == SpecialItemsToDelete.end())
                SpecialItemsToDelete[item_def_index] = items[i].second;
            else
                found->second += items[i].second;
        }
    }
    NotInStock.clear();
    if (false) {} else for (std::map<long,long>::const_iterator i = InventoryTradeThingsBuy.begin(); i != InventoryTradeThingsBuy.end(); ++i) {
        long thing_def_index = i->first;
        long number_of_items_to_add = i->second;
        if (number_of_items_to_add == 0) {
            if (!CTCInventoryItem::GetTattooCardDef(thing_def_index).Get() &&
                !CTCInventoryItem::GetHairCardDef(thing_def_index).Get()) {
                if (ptc_shop->GetMaxStock(thing_def_index))
                    NotInStock.push_back(thing_def_index);
            }
        } else if (CTCInventoryItem::IsBuyable(thing_def_index)) {
            AddItemOfTypeToInventory(thing_def_index, number_of_items_to_add);
            num_items_added += number_of_items_to_add;
            result.push_back(std::make_pair(thing_def_index, number_of_items_to_add));
        }
    }
    ItemBuyCount = num_items_added;
}
CComponent* CTCInventoryTrade::ConstructNormalShopListPC(const std::vector<std::pair<long, long> >& buyable,
                                                         const std::vector<std::pair<long, long> >& sellable)
{
    const CDataBank& rTextBank = CMainGameComponent::Get()->GetTextBank();
    CManager* pmanager = CManager::GetInstance();
    CComponent* plist_component = pmanager->CreateComponent("PC_TOP_LEVEL_TRADE_LIST", false);
    CList* plist = GFDebugPDynamicCast(plist_component, (CList*)0);
    CComponent* pparent = plist_component->FindChild("PC_MENU_ENTRY_TRADE_SELL");
    // what the pplayer can sell: the stock the shop deals in
    TotNumClothesToSell = TotNumWeaponsToSell = TotNumItemsToSell = 0;
    if (!sellable.empty()) {
        CTCShop* pTCShop = 0;
        CThing* pbuilding_thing = GetBuildingThing();
        pbuilding_thing->GetTC(&pTCShop);
        for (std::vector<std::pair<long, long> >::const_iterator it = sellable.begin(); it != sellable.end(); ++it) {
            if (pTCShop->IsValidStockItem(it->first)) {
                switch (GetTypeFromDefIndexPC(it->first)) {
                case MENU_TYPE_CLOTHING: TotNumClothesToSell += it->second; break;
                case MENU_TYPE_WEAPONS: TotNumWeaponsToSell += it->second; break;
                case MENU_TYPE_ITEMS:   TotNumItemsToSell += it->second; break;
                }
            }
        }
    }
    CWideString XString = CTCInventoryStats::GetXString();
    CWideString new_title = rTextBank.GetTextBySymbol("TEXT_GUI_MENU_SELL") + XString;
    new_title += GFIntToWideString(TotNumWeaponsToSell + TotNumItemsToSell + TotNumClothesToSell);
    CText* upper_menu_entry = GFDebugPDynamicCast(pparent->FindChild("PC_TRADING_SELL_TEXT"), (CText*)0);
    upper_menu_entry->SetValue(new_title, true, true);
    // what the pplayer can buy: affordable, room in the pplayer's ptc_inventory (or a special not yet owned)
    pparent = plist_component->FindChild("PC_MENU_ENTRY_TRADE_BUY");
    TotNumClothesToBuy = TotNumWeaponsToBuy = TotNumItemsToBuy = 0;
    if (!buyable.empty() || !NotInStock.empty()) {
        CTCShop* pTCShop = 0;
        CThing* pbuilding_thing = GetBuildingThing();
        pbuilding_thing->GetTC(&pTCShop);
        for (std::vector<std::pair<long, long> >::const_iterator it = buyable.begin(); it != buyable.end(); ++it) {
            long item_def = it->first;
            long quantity = it->second;
            const CThingPlayerCreature* pplayer = CMainGameComponent::Get()->PeekPlayerManager().GetMainPlayer().PeekPControlledCreature();
            const NInventory::CTCInventoryBase* ptc_inventory = 0;
            pplayer->PeekTC(CTCInventoryItem::GetInventoryType(item_def), &ptc_inventory);
            if (IsItemAffordable(item_def, 1) && (ptc_inventory->IsSpaceInInventoryForItem(item_def) || IsSpecialCase(item_def)) &&
                quantity > 0 && !AlreadyHaveSpecial(item_def)) {
                switch (GetTypeFromDefIndexPC(item_def)) {
                case MENU_TYPE_CLOTHING: TotNumClothesToBuy += it->second; break;
                case MENU_TYPE_WEAPONS: TotNumWeaponsToBuy += it->second; break;
                case MENU_TYPE_ITEMS:   TotNumItemsToBuy += it->second; break;
                }
            }
        }
    }
    new_title = rTextBank.GetTextBySymbol("TEXT_GUI_MENU_BUY") + XString;
    new_title += GFIntToWideString(TotNumWeaponsToBuy + TotNumItemsToBuy + TotNumClothesToBuy);
    upper_menu_entry = GFDebugPDynamicCast(pparent->FindChild("PC_TRADING_BUY_TEXT"), (CText*)0);
    upper_menu_entry->SetValue(new_title, true, true);
    // what the shop wants
    CTCShop* ptc_shop = 0;
    GetBuildingThing()->GetTC(&ptc_shop);
    std::vector<long> wanted_list = ptc_shop->GetWantedItemsList();
    pparent = plist_component->FindChild("PC_MENU_ENTRY_TRADE_WANTED");
    TotNumClothesWanted = TotNumWeaponsWanted = TotNumItemsWanted = 0;
    if (!wanted_list.empty()) {
        for (std::vector<long>::iterator it = wanted_list.begin(); it != wanted_list.end(); ++it) {
            switch (GetTypeFromDefIndexPC(*it)) {
            case MENU_TYPE_CLOTHING: ++TotNumClothesWanted; break;
            case MENU_TYPE_WEAPONS: ++TotNumWeaponsWanted; break;
            case MENU_TYPE_ITEMS:   ++TotNumItemsWanted; break;
            }
        }
    }
    new_title = rTextBank.GetTextBySymbol("TEXT_GUI_MENU_WANTED") + CTCInventoryStats::GetXString();
    new_title += GFIntToWideString(TotNumWeaponsWanted + TotNumItemsWanted + TotNumClothesWanted);
    upper_menu_entry = GFDebugPDynamicCast(pparent->FindChild("PC_TRADING_WANTED_TEXT"), (CText*)0);
    upper_menu_entry->SetValue(new_title, true, true);
    return plist_component;
}
void CTCInventoryTrade::ConstructActualInventoryPC()
{
    if (PSoundManager) {
        PSoundManager->SetGainFader(0x10, 0.0f, 500.0f);
        PSoundManager->SetGainFader(0x40, 0.0f, 500.0f);
        PSoundManager->SetGainFader(0x80, 0.0f, 500.0f);
    }
    ResetInventoryTradeItems();
    IsShoppingValid = GetInventoryShoppingValidity();
    std::vector<std::pair<long, long> > sellable;
    std::vector<std::pair<long, long> > buyable;
    std::vector<std::pair<long, long> > all_items;
    CTCShop* ptc_shop = 0;
    if (!GetBuildingThing()->GetTC(&ptc_shop)) { FABLE_RETAIL_ASSERT_ARM(false); }
    if (GetIsEnabled()) {
        if (!ptc_shop->IsBarberShop() && !ptc_shop->IsTattooShop() && !ptc_shop->IsTitleShop()) {
            InitialiseSellableItems();
            GetAllItems(sellable);
        }
        InitialiseBuyableItems(buyable);
        GetAllItems(all_items);
    }
    long thing_def_index = GetHighlightedItem();
    if (thing_def_index > 0)
        SetNumberOfSelectedItemOwned(thing_def_index);
    if (GetIsEnabled()) {
        NUISystem::CManager::GetInstance()->ClearActionParams();
        NUISystem::CManager::GetInstance()->SetInventoryTrade(this);
        if (ptc_shop->IsBarberShop()) {
            // a barber only deals in hair cards: drop every item without a hair-card def
            if (false) {} else for (std::vector<std::pair<long, long> >::iterator it = all_items.begin(); it != all_items.end(); ) {
                CDefPointer<const CHairCardDef> phair_card_def = CTCInventoryItem::GetHairCardDef(it->first);
                if (phair_card_def.IsNull())
                    it = all_items.erase(it);
                else
                    ++it;
            }
            CCharString name("PC_TOP_LEVEL_BARBER_LIST");
            PTop_Level_List = ConstructSpecialShopListPC(all_items, name);
        } else if (ptc_shop->IsTattooShop()) {
            // a tattooist only deals in valid tattoo cards
            if (false) {} else for (std::vector<std::pair<long, long> >::iterator it = all_items.begin(); it != all_items.end(); ) {
                CDefPointer<const CTattooDef> ptattoo_def = CTCInventoryItem::GetTattooCardDef(it->first);
                if (ptattoo_def.IsNull() || ptattoo_def->IsInvalidCustomTattoo())
                    it = all_items.erase(it);
                else
                    ++it;
            }
            CCharString name("PC_TOP_LEVEL_BARBER_LIST");
            PTop_Level_List = ConstructSpecialShopListPC(all_items, name);
        } else if (ptc_shop->IsTitleShop()) {
            CCharString name("PC_TOP_LEVEL_BARBER_LIST");
            PTop_Level_List = ConstructSpecialShopListPC(all_items, name);
        } else {
            // a normal shop leaves the hair and tattoo cards to the special shops
            if (false) {} else for (std::vector<std::pair<long, long> >::iterator it = buyable.begin(); it != buyable.end(); ) {
                if (CTCInventoryItem::GetTattooCardDef(it->first).Get() || CTCInventoryItem::GetHairCardDef(it->first).Get())
                    it = buyable.erase(it);
                else
                    ++it;
            }
            if (false) {} else for (std::vector<std::pair<long, long> >::iterator it = sellable.begin(); it != sellable.end(); ) {
                if (CTCInventoryItem::GetTattooCardDef(it->first).Get() || CTCInventoryItem::GetHairCardDef(it->first).Get())
                    it = sellable.erase(it);
                else
                    ++it;
            }
            PTop_Level_List = ConstructNormalShopListPC(buyable, sellable);
        }
    } else {
        AddCloseInventoryEvent();
    }
    if (PTop_Level_List) {
        PTop_Level_List->Initialise();
        PTop_Level_List->ChangeState(NUISystem::UI_STATE_LIST_ACTIVE);
        Components.push_back(PTop_Level_List);
    }
}

