/* Return an interface pointer to a requesting client
   performing a thread safe AddRef as necessary */

extern "C" HRESULT __stdcall GetInterface(IUnknown* pUnk, void** ppv)
{
    if (ppv == 0) return (HRESULT)0x80004003L;   // CheckPointer(ppv, E_POINTER)
    *ppv = pUnk;
    pUnk->AddRef();
    return 0;
}

HRESULT __stdcall CUnknown::NonDelegatingQueryInterface(const IID& riid, void** ppv)
{
    if (ppv == 0) return (HRESULT)0x80004003L;   // CheckPointer(ppv, E_POINTER)

    /* We know only about IUnknown */

    if (riid == IID_IUnknown) {
        GetInterface((IUnknown*)(INonDelegatingUnknown*)this, ppv);
        return 0;
    } else {
        *ppv = 0;
        return (HRESULT)0x80004002L;   // E_NOINTERFACE
    }
}