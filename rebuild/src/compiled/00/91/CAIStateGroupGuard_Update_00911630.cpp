void CAIStateGroup_Guard::Update()
{
    CIntelligentPointerTarget target(((CThingGuard*)PBrain->PCreature)->GetPGuardTarget());
    if (target.GetPItem()) {
        if (AIAction_LookAtThing(AI_ACTION_REPEAT_ONCE, target, 0x11, 0.0027777f) == AI_ACTION_RETURN_SUCCEEDED) {
            bool arrived = false;
            if (AIAction_MoveToThingProximity(AI_ACTION_REPEAT_ONCE, target, 2.0f, &arrived,
                    MOVEMENT_TYPE_WALK, true, false, true, true, 0.0f) == AI_ACTION_RETURN_SUCCEEDED)
                Terminate();
        }
    }
}