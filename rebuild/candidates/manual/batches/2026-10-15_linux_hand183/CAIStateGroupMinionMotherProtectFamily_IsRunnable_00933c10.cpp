// names a family member under threat that the mother can see; remember it in PFamilyMember.
// Retail: Fable.exe (TLC, VC7.1) function @ 0x00933C10, length 165 bytes (+ int3 padding).
// Callees: CVectorMap::LowerBound @ 0x004365B0 (inlined GetInterface, type 8 = bit 8 of the bitset dword at +0x20),
// the component's virtual slot 29 (+0x74, returns the threatened family thing), CanCreatureSeeCreature @ 0x008645E0
// (__fastcall viewer, target, false), the converting CIntelligentPointer temporary (vtable 0x0125AAEC):
// CBaseIntelligentPointer ctor @ 0x00A01B10, SetPItem @ 0x00A01B90 (twice), GetPItem @ 0x00A01B50, dtor @ 0x00A01C10.
// Shape: the GetInterface result is used straight as `this` in the virtual call (entry-returning lookup), then
// `PFamilyMember = thing` through the 8-byte temporary that reuses the key slot. No engine header for this class.
// ---- shared AI state-group model (same shapes as the landed CAIStateGroup_* sources) ----
struct CTCBase;
struct CThing;
