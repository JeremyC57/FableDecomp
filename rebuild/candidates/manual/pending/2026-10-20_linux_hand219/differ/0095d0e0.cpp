struct CAIStateGroup_RangedCombatUsePreferredFirePoint : CAIStateGroupBase {
    CBaseIntelligentPointer PEnemy;             // +0x14 CIntelligentPointer<CThingCreatureBase>
    CBaseIntelligentPointer PFirePoint;         // +0x1c CIntelligentPointer<CThing>
    long TimeOutCounter;                        // +0x24 (the frame of the last shot)
    bool IsStopping();                          // 0x008FD010
    CWorldF* GetPWorld();                       // 0x008FCFC0
    bool IsStillRunnable();
};

bool CAIStateGroup_RangedCombatUsePreferredFirePoint::IsStillRunnable()
{
    if (IS_THING_ALIVE(PFirePoint) && IS_THING_ALIVE(PEnemy) && !IsStopping()) {
        long lastShot = TimeOutCounter;
        if (lastShot > 0) {
            CTCEntityEvents* events;
            if (PBrain->PCreature->GetInterface(&events, 0x42)) {
                NEntityEvents::CEventFiredShot* shot;
                while (events->GetEvent(&shot, NEntityEvents::CIsEventCreatedAfter(lastShot))) {
                    long frame = shot->CreationFrame;
                    TimeOutCounter = frame;
                    lastShot = frame;
                }
            }
            long elapsed = GetPWorld()->GetWorldFrame() - TimeOutCounter;
            if (elapsed > g_framesPerSecond * 5)
                return false;
        }
        return true;
    }
    return false;
}
