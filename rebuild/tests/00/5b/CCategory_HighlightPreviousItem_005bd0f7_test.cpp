    static CItem items[4];
    for (int i = 0; i < 4; ++i) items[i].ItemType = 100 + i;
    CInventoryCategoryDef_Retail def; memset(((char*)&def) + 4, 0, sizeof(def) - 4); def.m_refCount = 1;
    CTCInventoryBase inv;
    CCategory_Retail c; memset(&c, 0, sizeof(c));
    c.ItemsInCategory.first = items; c.ItemsInCategory.last = items + 4; c.ItemsInCategory.end_of_storage = items + 4;
    c.PDef.m_pObject = &def; c.PInventory = &inv;
    // empty-slot mode: step back one slot
    def.SelectEmptySlots = true; c.HighlightedItemIndex = 2;
    c.HighlightPreviousItem();
    CHECK(c.HighlightedItemIndex == 1); CHECK(g_notified == 1); CHECK(g_notifiedType == 101);
    CHECK(def.m_refCount == 1); CHECK(g_destroyed == 0);       // the scoped def references are balanced
