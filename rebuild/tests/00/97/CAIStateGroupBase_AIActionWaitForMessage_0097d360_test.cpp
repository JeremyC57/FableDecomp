bool CAIStateGroupBaseAccess::IsStopping()
{
    ++stoppingChecks;
    return stopped || (stopOnCheck && stoppingChecks >= stopOnCheck);
}

CWorld* CAIStateGroupBaseAccess::GetPWorld()
{
    ++worldCalls;
    lastOperationWasWorld = 1;
    return (worldRotation++ & 1) ? &worldB : &worldA;
}

long FABLE_FASTCALL GetGameTick()
{
    int i = tickCalls++;
    if (!lastOperationWasWorld) badWorldBeforeTick = 1;
    lastOperationWasWorld = 0;
    if (!tickCount) return 0;
    return tickValues[i < tickCount ? i : tickCount - 1];
}

bool CMessageEventFilter_IsOfType::operator()(CMessageEvent* event) const
{
    int i = typeCalls++;
    if (i < 16) {
        typeValues[i] = Type;
        eventTypeValues[i] = event->Type;
    }
    if (mutateSentinelOnType && typeCalls == 1) {
        managerA.Messages = mutateSentinelOnType;
        managerB.Messages = mutateSentinelOnType;
    }
    return event && event->Type == Type;
}

CMessageEventFilter_IsOriginatedByThing::CMessageEventFilter_IsOriginatedByThing(
    const CThingCreatureBase* thing)
{
    if (thing != expectedOriginator) badOriginator = 1;
    // Actual constructor006AF290 reads the native CThing UID words at18/1c;
    // these inherited words are opaque named arrays in the actual creature header.
    memcpy(&UID[0], thing->_pad_0x18, sizeof(fable_u32));
    memcpy(&UID[1], thing->_pad_0x1c, sizeof(fable_u32));
}

bool CMessageEventFilter_IsOriginatedByThing::operator()(CMessageEvent* event) const
{
    ++originatorCalls;
    return event && event->OriginatorUID[0] == UID[0] && event->OriginatorUID[1] == UID[1];
}

CMessageEvent* CMessageEventManager::FindMostRecentMessage(const COwnMessageFilter& filter)
{
    SMessageNode* head = Messages;
    SMessageNode* node;
    ++managerQueries;
    if ((this != &managerA && this != &managerB) || !filter.TypeFilter || !filter.OriginatorFilter)
        badManager = 1;
    node = head->next;
    while (node != head) {
        CMessageEvent* event = &node->Event;
        if ((*filter.TypeFilter)(event) && (*filter.OriginatorFilter)(event)) {
            managerResult = event;
            return event;
        }
        node = node->next;
        head = Messages;
    }
    return 0;
}

