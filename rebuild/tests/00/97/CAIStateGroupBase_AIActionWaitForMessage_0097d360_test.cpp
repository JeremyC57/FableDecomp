static void linkList(SMessageNode* head, SMessageNode* nodes, int count)
{
    int i;
    head->next = count ? &nodes[0] : head;
    head->prev = count ? &nodes[count - 1] : head;
    for (i = 0; i < count; ++i) {
        nodes[i].prev = i ? &nodes[i - 1] : head;
        nodes[i].next = i + 1 < count ? &nodes[i + 1] : head;
    }
}

