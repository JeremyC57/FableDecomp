namespace std {
typedef pair<const unsigned long, long> CBattleEffectTreeValue;
typedef _Rb_tree<unsigned long, CBattleEffectTreeValue, _Select1st<CBattleEffectTreeValue>,
    less<unsigned long>, allocator<CBattleEffectTreeValue> > CBattleEffectTree;
template<> template<> inline
_Rb_tree_node<CBattleEffectTreeValue>* CBattleEffectTree::_M_find<unsigned long>(const unsigned long& key) const
{
    _Link_type y = this->_M_header._M_data;
    _Link_type x = _M_root();
    while (x != 0) {
        if (!_M_key_compare(_S_key(x), key)) {
            y = x;
            x = _S_left(x);
        } else {
            x = _S_right(x);
        }
    }
    if (y == this->_M_header._M_data || _M_key_compare(key, _S_key(y)))
        y = this->_M_header._M_data;
    return y;
}
}

