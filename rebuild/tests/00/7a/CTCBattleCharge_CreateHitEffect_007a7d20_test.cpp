static unsigned long EffectKey(const char* name)
{
    unsigned long crc = 0;
    for (;*name;++name)
        crc = g_CRCTable[static_cast<unsigned char>(*name) ^ (crc & 0xff)] ^ (crc >> 8);
    return crc;
}

static void PopulateEffects()
{
    typedef std::_Rb_tree_node<std::CBattleEffectTreeValue> EffectNode;
    static Storage<EffectNode> nodes[9];
    std::CBattleEffectTree& tree = effect_def->SpecialEffectsMap.ContainmentMap._M_t;
    std::_Rb_tree_node_base* header = tree._M_header._M_data;
    header->_M_parent = 0;
    for (unsigned i = 0; i < 9; ++i) {
        if (!want_effect[i])
            continue;
        const unsigned long key = EffectKey(effect_names[i]);
        EffectNode* node = nodes[i].Get();
        new (&node->_M_value_field) std::CBattleEffectTreeValue(key, 100+i);
        node->_M_left = 0;
        node->_M_right = 0;
        std::_Rb_tree_node_base* parent = header;
        std::_Rb_tree_node_base** link = &header->_M_parent;
        while (*link) {
            parent = *link;
            const EffectNode* current = static_cast<EffectNode*>(parent);
            link = key < current->_M_value_field.first ? &parent->_M_left : &parent->_M_right;
        }
        node->_M_parent = parent;
        *link = node;
    }
}

static void RecordEffectQuery(const char* name)
{
    for (unsigned i=0; i<9; ++i) {
        if (!strcmp(name,effect_names[i])) {
            Check(effect_queries<12);
            effect_order[effect_queries++]=i;
            return;
        }
    }
}


