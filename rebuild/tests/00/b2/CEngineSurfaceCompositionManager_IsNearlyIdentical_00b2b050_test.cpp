static void SetBlend(CCompositeBlendDesc& d, unsigned long tex, long type, unsigned char r, unsigned char g, unsigned char b, unsigned char a,
                     unsigned char sr, unsigned char sg, unsigned char sb, unsigned char sa)
{
    d.TextureIndex = tex; d.BlendType = type;
    d.DiffuseColour.R = r; d.DiffuseColour.G = g; d.DiffuseColour.B = b; d.DiffuseColour.A = a;
    d.SpecularColour.R = sr; d.SpecularColour.G = sg; d.SpecularColour.B = sb; d.SpecularColour.A = sa;
}
static void SetMorph(CEngineTextureMorph& m, CCompositeBlendDesc* blends, unsigned int n)
{
    m.OriginalTextureIndex = 0; m.MorphID = 0;
    m.Blends._M_start = blends; m.Blends._M_finish = blends + n; m.Blends._M_end_of_storage = blends + n;
}
