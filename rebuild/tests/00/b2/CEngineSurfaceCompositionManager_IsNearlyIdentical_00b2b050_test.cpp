    SetBlend(a3[1], 6, 1, 100, 100, 100, 100, 0, 0, 0, 0);
    SetBlend(a3[2], 7, 2, 255, 0, 255, 0, 9, 9, 9, 9);
    for (int k = 0; k < 3; ++k) b3[k] = a3[k];
    b3[1].BlendType = 9;                                   // BlendType is not compared
