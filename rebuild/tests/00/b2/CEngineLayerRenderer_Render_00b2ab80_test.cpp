static void log_event(int event, const CEngineComponentRenderParams& params)
{
    g_ok = g_ok && params.Params == g_expectedParams &&
           params.RenderLayer == g_expectedLayer &&
           params.RenderLayerFlags == g_expectedFlags;
    g_events[g_eventCount++] = event;
}

struct TestComponent : CEngineComponentDispatch {
    unsigned long filterMask;
    int identity;
    int filterCalls;
    CEngineLayerRenderer* appendRenderer;
    CEngineComponent* appendComponent;

    TestComponent(unsigned long mask, int id)
        : filterMask(mask), identity(id), filterCalls(0), appendRenderer(0), appendComponent(0)
    {
        GlobalPointerAddress = 0;
        RenderEnabled = false;
        KeepAlive = 0;
        _pad_0x0a[0] = _pad_0x0a[1] = 0;
    }

    virtual ~TestComponent() { }
    virtual void FrameStart(const CEngineComponentParams&) { }
    virtual void FrameEnd(const CEngineComponentParams&) { }
    virtual bool LoadNewScene(const CEngineComponentLoadNewSceneParams&) { return false; }
    virtual void Render(const CEngineComponentRenderParams& params)
    {
        log_event(identity + 2, params);
    }
    virtual void PreLayerRender(const CEngineComponentRenderParams& params)
    {
        log_event(identity + 1, params);
        if (appendRenderer && appendComponent) {
            if (appendRenderer->Components.Last == appendRenderer->Components.First + 1) {
                appendRenderer->Components.First[1] = appendComponent;
                ++appendRenderer->Components.Last;
            }
            appendRenderer = 0;
            appendComponent = 0;
        }
    }
    virtual void PostLayerRender(const CEngineComponentRenderParams& params)
    {
        log_event(identity + 3, params);
    }
    virtual void WorldFrameUpdate(bool) { }
    virtual void PausedWorldFrameUpdate() { }
    virtual CCharString GetConsoleEnableFunctionName() { return CCharString(); }
    virtual unsigned long GetSceneFilterFlags()
    {
        ++filterCalls;
        return filterMask;
    }
    virtual void OnReleaseDefaultPoolResources() { }
    virtual bool OnRestoreDefaultPoolResources() { return true; }
};

static bool has_events(const int* expected, int count)
{
    if (g_eventCount != count)
        return false;
    for (int i = 0; i < count; ++i)
        if (g_events[i] != expected[i])
            return false;
    return true;
}

int main()
{
    CEngineComponentParams params;
    params.SceneFilterFlags = 3;
    CEngineLayerRenderer renderer(static_cast<EEngineRenderLayer>(7),
                                  static_cast<ERenderRenderLayerFlags>(5), 1);
    CEngineComponent* items[3];
    TestComponent first(1, 10);
    TestComponent second(2, 20);
    first.RenderEnabled = true;
    second.RenderEnabled = false;
    items[0] = reinterpret_cast<CEngineComponent*>(&first);
    items[1] = 0;
    items[2] = 0;
    if (g_baseClassCtorCalls != 1 || g_nonCopyableCtorCalls != 1 ||
        renderer.Layer != static_cast<EEngineRenderLayer>(7) ||
        renderer.Flags != static_cast<ERenderRenderLayerFlags>(5) ||
        renderer.SceneFilterFlags != 1 || renderer.Components.First != 0 ||
        renderer.Components.Last != 0 || renderer.Components.End != 0)
        g_ok = false;
    renderer.Components.First = items;
    renderer.Components.Last = items + 1;
    renderer.Components.End = items + 3;
    first.appendRenderer = &renderer;
    first.appendComponent = reinterpret_cast<CEngineComponent*>(&second);
    g_expectedParams = &params;
    g_expectedLayer = renderer.Layer;
    g_expectedFlags = renderer.Flags;

    renderer.Render(params);
    const int expected[] = { 11, 21, 12, 13, 23 };
    g_ok = g_ok && has_events(expected, 5) &&
           renderer.Components.Last == items + 2 &&
           first.filterCalls == 3 && second.filterCalls == 3;

    const int beforeGate = g_eventCount;
    const int firstQueries = first.filterCalls;
    renderer.SceneFilterFlags = 4;
    renderer.Render(params);
    g_ok = g_ok && g_eventCount == beforeGate && first.filterCalls == firstQueries;

    renderer.SceneFilterFlags = 3;
    first.filterMask = 0;
    second.filterMask = 0;
    g_eventCount = 0;
    renderer.Render(params);
    g_ok = g_ok && g_eventCount == 0 && first.filterCalls == 6 && second.filterCalls == 6;

    {
        CEngineLayerRenderer destructorCheck(static_cast<EEngineRenderLayer>(2),
                                             static_cast<ERenderRenderLayerFlags>(3), 0);
    }
    g_ok = g_ok && g_baseClassCtorCalls == 2 && g_nonCopyableCtorCalls == 2 &&
           g_baseClassDtorCalls == 1 && g_nonCopyableDtorCalls == 1;

    std::printf(g_ok ? "00b2ab80_TEST PASS\n" : "00b2ab80_TEST FAIL\n");
    return g_ok ? 0 : 1;
}