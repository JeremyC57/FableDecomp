struct CDefPointerTrophyDef {
    const CTrophyDef* Object;
};

class CWorld { public:
    static long GetWorldFrame();            // 0x0049D870
};

extern long g_FramesPerSecond;              // 0x01375550

class CTCTrophy { public:
    void*                __vftable;         // +0x00
    unsigned char        _pad_0x04[0x8];
    CDefPointerTrophyDef PDef;              // +0x0C
    unsigned char        _pad_0x10[0x1C];
    long                 PendingGainedWitnessSounds;        // +0x2C
    long                 FrameForNextGainedWitnessSound;    // +0x30
    unsigned long PlaySoundW(const CCharString& name);      // 0x006DDCD0
    void UpdateGainedWitnessSounds();
};

void CTCTrophy::UpdateGainedWitnessSounds()
{
    if (PendingGainedWitnessSounds > 0 && CWorld::GetWorldFrame() > FrameForNextGainedWitnessSound) {
        PlaySoundW(*(const CCharString*)&PDef.Object->SoundGainedWitness_PStringData);
        const CTrophyDef* def = PDef.Object;
        --PendingGainedWitnessSounds;
        long framesPerSecond = g_FramesPerSecond;
        FrameForNextGainedWitnessSound = (long)(framesPerSecond * def->SecsDelayPerGainedWitnessSound + CWorld::GetWorldFrame());
    }
}

// ---- stubs and driver ----
long g_FramesPerSecond = 30;
static long g_frames[4]; static int g_frameCalls = 0;
long CWorld::GetWorldFrame() { return g_frames[g_frameCalls++]; }
static const CCharString* g_played; static CTCTrophy* g_playThis; static int g_plays = 0;
unsigned long CTCTrophy::PlaySoundW(const CCharString& name) { ++g_plays; g_played = &name; g_playThis = this; return 7; }
static CTrophyDef g_def;
int main()
{
    g_def.SecsDelayPerGainedWitnessSound = 2.5f;
    g_def.SoundGainedWitness_PStringData = (CCharStringData*)0x1234;
    CTCTrophy t; t.__vftable = 0; t.PDef.Object = &g_def;
    // 1) nothing pending: no frame read, nothing played
    t.PendingGainedWitnessSounds = 0; t.FrameForNextGainedWitnessSound = 5; g_frameCalls = 0;
    t.UpdateGainedWitnessSounds();
    CHECK(g_frameCalls == 0 && g_plays == 0 && t.FrameForNextGainedWitnessSound == 5);
    // 2) pending but not yet time (frame == next): no play
    t.PendingGainedWitnessSounds = 2; g_frames[0] = 5; g_frameCalls = 0;
    t.UpdateGainedWitnessSounds();
    CHECK(g_frameCalls == 1 && g_plays == 0 && t.PendingGainedWitnessSounds == 2);
    // 3) time has come: play, count off, next = (long)(30 * 2.5 + 100) = 175
    g_frames[0] = 6; g_frames[1] = 100; g_frameCalls = 0;
    t.UpdateGainedWitnessSounds();
    CHECK(g_frameCalls == 2 && g_plays == 1 && g_playThis == &t && g_played == (const CCharString*)&g_def.SoundGainedWitness_PStringData);
    CHECK(t.PendingGainedWitnessSounds == 1 && t.FrameForNextGainedWitnessSound == 175);
    // 4) truncation: fps 25, delay 0.3 -> 7.5 + 200 = 207.5 -> 207
    g_FramesPerSecond = 25; g_def.SecsDelayPerGainedWitnessSound = 0.3f; g_frames[0] = 176; g_frames[1] = 200; g_frameCalls = 0;
    t.UpdateGainedWitnessSounds();
    CHECK(g_plays == 2 && t.PendingGainedWitnessSounds == 0 && t.FrameForNextGainedWitnessSound == 207);
    if (fails == 0) printf("006dee80_TEST PASS\n");
    return fails;
}
