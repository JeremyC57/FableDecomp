void CCharString::UnassignString()
{
    if (storage_) {
        if (--storage_->owners == 0) {
            std::free(storage_->text);
            std::free(storage_);
            --g_liveStringData;
        }
        storage_ = 0;
    }
}
CCharStringData* CCharString::AllocStringData(const char* text, long length)
{
    if (length < 0) length = (long)std::strlen(text);
    CCharStringData* d = (CCharStringData*)std::malloc(sizeof(CCharStringData));
    d->text = (char*)std::malloc((size_t)length + 1);
    std::memcpy(d->text, text, (size_t)length);
    d->text[length] = 0;
    d->unknown04 = d->unknown08 = 0;
    d->flags0C = 0;
    d->owners = 1;
    ++g_liveStringData;
    return d;
}
