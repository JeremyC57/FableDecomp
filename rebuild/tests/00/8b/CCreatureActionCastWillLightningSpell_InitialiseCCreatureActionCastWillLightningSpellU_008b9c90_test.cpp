static CBaseObjectPointer* RecordFor(CThing* key, bool create)
{
    int i;
    for (i=0; i<g_recordSlots; ++i) if (g_records[i].key == key) return g_records[i].record;
    if (!create || !key) return 0;
    CBaseObjectPointer* p = new CBaseObjectPointer;
    p->Object = key; p->refs = 0; // native refs count intelligent pointers only
    g_records[g_recordSlots].key=key; g_records[g_recordSlots].record=p; ++g_recordSlots;
    ++g_recordLive; ++g_recordAllocs;
    return p;
}
static void MaybeDeleteRecord(CBaseObjectPointer* p)
{
    int i;
    if (!p || p->Object || p->refs) return;
    for (i=0; i<g_recordSlots; ++i) if (g_records[i].record==p) {
        g_records[i]=g_records[g_recordSlots-1]; --g_recordSlots; break;
    }
    delete p; --g_recordLive; ++g_recordDeletes;
}
static void ReleasePointer(CBaseObjectPointer* p)
{
    if (p && p->refs) { --p->refs; MaybeDeleteRecord(p); }
}
static void MarkThingDead(CThing* key)
{
    CBaseObjectPointer* p=RecordFor(key,false);
    int i;
    if (p && p->Object) { p->Object=0; MaybeDeleteRecord(p); }
    for (i=0; i<g_componentSlots; ++i) if (g_components[i].key==key) {
        delete g_components[i].component;
        g_components[i]=g_components[g_componentSlots-1]; --g_componentSlots; break;
    }
}
