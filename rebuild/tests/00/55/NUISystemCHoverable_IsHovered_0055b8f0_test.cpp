static bool check(HoverFixture& h,long x,long y,bool expected) {
    C2DBoxI mouse;mouse.TLX=x;mouse.TLY=y;mouse.BRX=-999;mouse.BRY=-999;
    h.Calls=0; return h.IsHovered(mouse)==expected && h.Calls==3;
}
