#!/usr/bin/env python3
"""assemble.py <agent folder> <triage GEN.tsv> <batch dir>... (NF324, 2026-11-24; repo root): the hand-back tables from the triage and
the exported batches. Every ENTRIES address gets one STATUS line from the LAST batch dir that has it (pass first-grade exports first and
final exports last): ACCEPT is `done`, REJECT is `rejected` (also in REJECTED.tsv), a batch SKIP keeps its reason, and an address no batch
reached keeps the triage reason. work/holds.tsv addresses are `skipped-held`. Writes STATUS.tsv, RENAMES.tsv, APPLIED.tsv, REJECTED.tsv,
TABLE_CHANGES.tsv (concatenated batch tables), rows.txt (done addresses) and rows/<addr>.cpp copies (rows/ must be empty first)."""
import os, re, sys, shutil, collections
A, genf, batches = sys.argv[1], sys.argv[2], sys.argv[3:]
sys.path.insert(0, "tools/decomp_pipeline"); import naming_status as ns
ent = ns.landed_rows()
E = [l.split("\t") for l in open(f"{A}/ENTRIES.tsv").read().splitlines()[1:]]
G = {l.split("\t")[0]: l.split("\t") for l in open(genf).read().splitlines()[1:]}
R = {}
for b in batches:
    for l in open(f"{b}/RESULTS.tsv").read().splitlines()[1:]:
        q = l.split("\t")
        R[q[0]] = q + [b]   # the LAST batch dir that has the address wins: pass first-grade exports first, final exports last
def status(why):
    w = why.lower()
    if w.startswith("done:"): return "skipped-held"   # already done by another landing (reason says which)
    if w.startswith(("identity:", "reserved", "lock held")) or "no landed / non-_pass switch" in w or "needs" in w and "undefined" in w: return "skipped-held"
    return "skipped-port"
st, ren, app = [], [], []
_oh = open("rebuild/candidates/manual/naming/status/OPEN.tsv").readline().rstrip("\n").split("\t")
CAT = {l.split("\t")[0]: l.rstrip("\n").split("\t")[_oh.index("catalog")] for l in open("rebuild/candidates/manual/naming/status/OPEN.tsv").read().splitlines()[1:]}   # old catalog name as the tracker shows it
HOLD = {}   # manual holds found after grading (census): address -> reason
if os.path.exists(f"{A}/work/holds.tsv"):
    for l in open(f"{A}/work/holds.tsv").read().splitlines():
        if l.strip(): HOLD[l.split("\t")[0]] = l.split("\t", 1)[1]
os.makedirs(f"{A}/rows", exist_ok=True)
assert not os.listdir(f"{A}/rows"), "rows/ is not empty: clean it with clean.py first"
for t, s, p, src, *_ in E:
    if t in HOLD:
        st.append((t, "skipped-held", p, HOLD[t]))
    elif t in R and R[t][1] == "ACCEPT":
        r = R[t]; st.append((t, "done", p, f"{os.path.relpath(r[5], A)}: {r[4]}"))
        meth, cls = re.match(r'\?([^@]+)@([^@]+)@@', p).groups()
        ren.append((f"0x{t.upper()}", cls, meth, p, CAT.get(t) or f"{cls}::{meth}", r[2],
                    f"RTTI vftable placement (ghidra_out/labels_rtti_port.tsv) names {p} here + PDB name set; flatten_pilot v4 {r[4]}"))
        app.append((f"0x{t.upper()}", ent[t]["Source"], f"flatten v4: {r[2]} -> {p} ({r[4]})"))
        shutil.copy(f"{r[5]}/rows/{t}.cpp", f"{A}/rows/{t}.cpp")
    elif t in R:
        r = R[t]; why = r[4]
        if r[1] == "REJECT":   # classify (advisor 2026-11-24)
            if "differ" in why.lower() and ".text" in why and re.search(r'@@[A-Z][AB]E(_N|X)', p) and not re.search(r'@@Y[AGI](_N|X)', s): why += " [return width: retail keeps the self's int / byte return where the PDB says bool / void: NF317 Q4, a PDB revision difference, not respelled]"
            elif "+__fltused -" in why: why += " [UND delta exactly __fltused: NF321 Q1 candidate]"
            elif "NOT_GRADED" in why: why += " [chunk timeout: retry]"
            g = G.get(t)
            if g and g[1] != "GEN": why += f" [the final tool now skips it: {g[5]}]"
        if "NOT_GRADED" in why: print("WARNING: NOT_GRADED in the last batch for", t, "- regrade it")
        st.append((t, "rejected" if r[1] == "REJECT" else status(why), p, f"{os.path.relpath(r[5], A)} {r[1]}: {why}"))
    else:
        g = G.get(t)
        why = g[5] if g else "not reached"
        if g and g[1] == "GEN": print("WARNING: generated by the triage run but in no batch:", t)
        st.append((t, status(why), p, f"triage ({g[4] if g else '-'}): {why}"))
with open(f"{A}/STATUS.tsv", "w") as o:
    o.write("address\tstatus\tpdb_spelling\treason\n" + "".join("\t".join(x) + "\n" for x in st))
with open(f"{A}/RENAMES.tsv", "w") as o:
    o.write("address\tmodule\tname\tmangled_leaf\told_catalog_name\told_leaf\tevidence\n" + "".join("\t".join(x) + "\n" for x in ren))
with open(f"{A}/APPLIED.tsv", "w") as o:
    o.write("address\tfile\tchange\n" + "".join("\t".join(x) + "\n" for x in app))
tc = ["action\tsymbol\ttarget\twitness\tnote"]
for b in batches:
    if os.path.exists(f"{b}/TABLE_CHANGES.tsv"): tc += open(f"{b}/TABLE_CHANGES.tsv").read().splitlines()[1:]
open(f"{A}/TABLE_CHANGES.tsv", "w").write("\n".join(tc) + "\n")
with open(f"{A}/REJECTED.tsv", "w") as o:
    o.write("address\tpdb_spelling\treason\n" + "".join(f"{x[0]}\t{x[2]}\t{x[3]}\n" for x in st if x[1] == "rejected"))
open(f"{A}/rows.txt", "w").write("".join(x[0] + "\n" for x in st if x[1] == "done"))
print(collections.Counter(x[1] for x in st))
